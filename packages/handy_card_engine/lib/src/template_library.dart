/// How many different layouts the library holds (before looks).
int get libraryLayoutCount => _layouts.length;

List<CardTemplate> _library() => [
  for (final (i, l) in _layouts.indexed)
    for (final lookId in l.looks)
      CardTemplate(
        '${l.id}-$lookId',
        '${l.en} · ${_looks[lookId]!.en}',
        '${l.vi} · ${_looks[lookId]!.vi}',
        l.kind,
        (r, at) {
          final k = _looks[lookId]!;
          final size = cardSizes.firstWhere((s) => s.id == l.size);
          final w = l.portrait
                  ? math.min(size.widthPt, size.heightPt)
                  : size.widthPt,
              h = l.portrait
                  ? math.max(size.widthPt, size.heightPt)
                  : size.heightPt;
          final c = _Kit(r, k, w, h);
          final back = l.kind == 'business'
              ? _backs[i % _backs.length](c)
              : <CardElement>[];
          return _doc(
            l.kind,
            l.en,
            size,
            at,
            l.front(c),
            back,
            frontBg: k.bg,
            backBg: k.bg,
            portrait: l.portrait,
            oneSide: l.kind != 'business',
          );
        },
      ),
];
