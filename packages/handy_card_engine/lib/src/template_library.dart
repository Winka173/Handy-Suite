typedef _Els = List<CardElement>;

class _Kit {
  final ElementRegistry r;
  final _Look k;
  final double w, h;
  const _Kit(this.r, this.k, this.w, this.h);

  CardElement text(
    String value,
    double x,
    double y,
    double width,
    double height, {
    double size = 9,
    bool title = false,
    String? color,
    String align = 'left',
    String? bind,
    double? weight,
    bool upper = false,
    double spacing = 0,
    double rotation = 0,
  }) => _el(
    r,
    bind != null && bind != 'name' && bind != 'role' && bind != 'org'
        ? 'contact'
        : 'text',
    x,
    y,
    width,
    height,
    bind: bind,
    rotation: rotation,
    props: {
      'text': value,
      'size': size,
      'font': title ? k.title : k.body,
      'weight': weight ?? (title ? k.weight : 400),
      'color': color ?? (title ? k.ink : k.ink),
      'align': align,
      'upper': upper,
      'letterSpacing': spacing,
    },
  );

  CardElement rect(
    double x,
    double y,
    double width,
    double height, {
    String? fill,
    String? stroke,
    double strokeWidth = 1,
    double radius = 0,
  }) => _el(
    r,
    'rect',
    x,
    y,
    width,
    height,
    props: {
      'fill': fill,
      'stroke': stroke,
      'strokeWidth': strokeWidth,
      'radius': radius,
    },
  );

  CardElement ellipse(
    double x,
    double y,
    double width,
    double height, {
    String? fill,
    String? stroke,
    double strokeWidth = 1,
  }) => _el(
    r,
    'ellipse',
    x,
    y,
    width,
    height,
    props: {'fill': fill, 'stroke': stroke, 'strokeWidth': strokeWidth},
  );

  CardElement qr(double x, double y, double side, {String bind = 'vcard'}) =>
      _el(
        r,
        'qr',
        x,
        y,
        side,
        side,
        bind: bind,
        props: {'color': k.bg == 'FFFFFF' ? k.ink : '111111'},
      );

  CardElement photo(
    double x,
    double y,
    double width,
    double height, {
    String mask = 'none',
  }) => _el(r, 'image', x, y, width, height, props: {'mask': mask});

  /// The look's ornament at ([x], [y]), [u] points tall.
  _Els orn(double x, double y, double u) => switch (k.orn) {
    'rule' => [
      _el(
        r,
        'line',
        x,
        y,
        u * 3,
        2,
        props: {'stroke': k.accent, 'strokeWidth': u / 8},
      ),
    ],
    'ring' => [ellipse(x, y, u, u, stroke: k.accent, strokeWidth: u / 9)],
    'bar' => [rect(x, y, u * 2, u * .4, fill: k.accent)],
    'hex' => [
      _el(r, 'polygon', x, y, u, u, props: {'sides': 6, 'fill': k.accent}),
    ],
    _ => [
      for (var i = 0; i < 3; i++)
        ellipse(x + i * u * .55, y, u * .35, u * .35, fill: k.accent),
    ],
  };

  /// Phone, email and website under each other (or [only] some of them).
  _Els contacts(
    double x,
    double y, {
    double width = 180,
    double size = 7.5,
    double gap = 14,
    String align = 'left',
    String? color,
    List<String> only = const ['phone', 'email', 'website'],
    bool icons = true,
  }) {
    const sample = {'phone': _phone, 'email': _mail, 'website': _web};
    const glyphs = {'phone': 'phone', 'email': 'mail', 'website': 'web'};
    final out = <CardElement>[];
    for (final (i, f) in only.indexed) {
      final top = y + i * gap;
      if (icons && align == 'left') {
        out.add(
          _el(
            r,
            'icon',
            x,
            top + size * .15,
            size,
            size,
            props: {'glyph': glyphs[f], 'color': color ?? k.accent},
          ),
        );
      }
      out.add(
        text(
          sample[f]!,
          icons && align == 'left' ? x + size * 1.8 : x,
          top,
          icons && align == 'left' ? width - size * 1.8 : width,
          size * 1.6,
          size: size,
          bind: f,
          align: align,
          color: color,
        ),
      );
    }
    return out;
  }
}

class _Layout {
  final String id, en, vi, kind, size;
  final bool portrait;
  final List<String> looks;
  final _Els Function(_Kit) front;
  const _Layout(
    this.id,
    this.en,
    this.vi,
    this.kind,
    this.size,
    this.looks,
    this.front, {
    this.portrait = false,
  });
}

