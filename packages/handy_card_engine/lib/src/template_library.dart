// The template library: layouts made for Handy Card, each drawn in a few
// looks. A look is a palette, a pair of faces and an ornament (a rule, a
// ring, a bar, a hexagon or dots), so the same layout in two looks differs
// in shape as well as colour; a test checks that no two templates share
// their front page's geometry. Every element stays editable and contact
// fields bind to the profile.

class _Look {
  final String id, en, vi, bg, ink, muted, accent, onAccent;
  final String title, body, orn;
  final double weight;
