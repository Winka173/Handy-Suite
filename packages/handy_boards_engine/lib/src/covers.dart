final Map<String, CoverDef> _coverIndex = {
  for (final cover in coverCatalog) cover.id: cover,
};

CoverDef? coverById(String? id) => _coverIndex[id];
Iterable<CoverDef> coversIn(CoverFamily f) =>
    coverCatalog.where((cover) => cover.family == f);
String familyNameEn(CoverFamily f) => switch (f) {
  CoverFamily.study => 'Study',
  CoverFamily.work => 'Work',
  CoverFamily.goals => 'Goals',
  CoverFamily.shopping => 'Shopping',
  CoverFamily.home => 'Home',
  CoverFamily.creative => 'Creative',
