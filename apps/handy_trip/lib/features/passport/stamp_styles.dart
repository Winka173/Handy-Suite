/// The stamp styles of the workshop. Each is a different cut (shape and
/// edge), ornament and line weight; the ink is only a suggestion the person
/// can change, so no two styles differ by colour alone (a test checks it).
class StampStyle {
  final String id, family, shape, edge, decor;
  final bool thin;
  final int ink;
  const StampStyle(
    this.id,
    this.family,
    this.shape,
    this.edge,
    this.decor, {
    this.thin = false,
    required this.ink,
  });

  /// What makes it a different design: everything but the ink.
  String get signature => '$shape/$edge/$decor/${thin ? 'thin' : 'bold'}';
}

